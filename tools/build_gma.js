// Build the .gma with gmad, the tool that ships with Garry's Mod.
//
//   node tools/build_gma.js [output.gma]
//
// gmad does the packing: the format is its business, not ours. This script
// does the two things around it that have to be right.
//
//   1. The version stamp. It records the commit the .gma was built from, and
//      it is generated rather than committed (it records a commit, so
//      committing it would change the commit it records). Building from the
//      source tree means the stamp has to be written HERE, or the addon
//      reports "unknown" as its build.
//
//   2. The build itself, from the source tree, with gmad told to skip
//      invalid files - a stray file that is not a real asset should not
//      stop a release.
//
// The source tree is the only build source. The deployed clone under the
// game's addons folder is a deploy target, not a build artefact: it is
// removed once the .gma is built, or the addon is loaded twice.

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const SRC = process.cwd();
const OUT = process.argv[2] || path.join(SRC, "ntx_audio.gma");
const GMAD = process.env.GMAD
  || "C:/Program Files (x86)/Steam/steamapps/common/GarrysMod/bin/gmad.exe";
const VERSION_REL = "lua/autorun/ntx_version.lua";

if (!fs.existsSync(GMAD)) {
  console.error(`gmad not found at ${GMAD}`);
  console.error("Set GMAD to the path of gmad.exe, or install Garry's Mod.");
  process.exit(1);
}

const hash = execSync("git rev-parse --short HEAD", { cwd: SRC, encoding: "utf8" }).trim();

// Written into the source tree, which is gitignored - the same file the
// deploy script writes into the clone, so both build paths stamp the same
// way.
fs.writeFileSync(
  path.join(SRC, VERSION_REL),
  `-- GENERATED by tools/build_gma.js. Do not edit, do not commit.\n` +
    `NTx = NTx or {}\n` +
    `NTx.COMMIT = "${hash}"\n` +
    `print("[NTx] " .. NTx.COMMIT .. (CLIENT and " (client)" or " (server)"))\n`,
  "utf8"
);
console.log(`stamped ${hash}`);

execSync(
  `"${GMAD}" create -folder "${SRC}" -out "${OUT}" -warninvalid`,
  { cwd: SRC, stdio: "inherit" }
);

const mb = (fs.statSync(OUT).size / 1048576).toFixed(1);
console.log(`\n${OUT} (${mb} MiB) built from commit ${hash}`);
console.log("check it with: node tools/verify_gma.js . " + path.basename(OUT));
