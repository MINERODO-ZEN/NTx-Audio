// Deploy the addon to the GMod addons folder, stamp it with its commit, and
// optionally copy the WebAudio page somewhere for upload.
//
//   node tools/sync.js [pageCopyPath]
//
// Replaces four manual steps that kept drifting apart. The page copy in
// particular was forgotten more than once, and a page that is stale on the
// remote host looks exactly like a client that is stale on disk - the audio
// keeps arriving with none of the per-bus selection in it.
//
// Why the version file is generated and NOT committed: it records a commit, so
// committing it would change the commit it records and it could never match.
// It is written after the reset and is gitignored, which also means a reset
// cannot wipe it before it is rewritten.
//
// shortcut: the stamp records what was DEPLOYED, not what HEAD is now. A later
// `git pull` in the source without re-running this reports the older deploy,
// which is the truth about what the running addon contains.

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const ADDON = "C:/Program Files (x86)/Steam/steamapps/common/GarrysMod/garrysmod/addons/NTx";
const SRC = process.cwd();
const VERSION_REL = "lua/autorun/ntx_version.lua";
const PAGE_REL = "data_static/ntx_audio/webaudio.html";

const pageCopy = process.argv[2];

function git(args, cwd) {
  return execSync(`git ${args}`, { cwd, encoding: "utf8" }).trim();
}

const hash = git("rev-parse --short HEAD", SRC);
console.log(`deploying ${hash}`);

git(`fetch "${SRC}" testing`, ADDON);
git("reset --hard FETCH_HEAD", ADDON);

// Written after the reset on purpose - see the header note.
fs.writeFileSync(
  path.join(ADDON, VERSION_REL),
  `-- GENERATED by tools/sync.js. Do not edit, do not commit.\n` +
    `NTx = NTx or {}\n` +
    `NTx.COMMIT = "${hash}"\n` +
    `print("[NTx] " .. NTx.COMMIT .. (CLIENT and " (client)" or " (server)"))\n`,
  "utf8"
);

if (pageCopy) {
  const dest = path.resolve(pageCopy);
  fs.copyFileSync(path.join(SRC, PAGE_REL), dest);
  console.log(`page copied to ${dest}`);
}

console.log(`ok - ${git("log --oneline -1", ADDON)}`);
